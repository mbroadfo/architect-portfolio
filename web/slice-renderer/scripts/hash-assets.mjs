// Writes src/static-assets.ts with the content hash of each static asset, so pages can
// reference "/assets/{name}.{hash}.{ext}" while rendering stays pure (C11).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const assets = [{ name: "site", ext: "css", source: "assets/site.css" }];

const entries = assets.map(({ name, ext, source }) => {
  const hash = createHash("sha256").update(readFileSync(source)).digest("hex").slice(0, 10);
  return `  ${name}: { path: "/assets/${name}.${hash}.${ext}", source: "${source}" },`;
});

const output = [
  "// Generated by scripts/hash-assets.mjs. Do not edit; run `npm run hash-assets`.",
  "export const STATIC_ASSETS = {",
  ...entries,
  "} as const;",
  "",
].join("\n");

writeFileSync("src/static-assets.ts", output);
