// Builds the public static assets and writes src/static-assets.ts with the content hash of
// each, so pages can reference "/assets/{name}.{hash}.{ext}" while rendering stays pure (C11).
//
//   1. src/client/main.ts is bundled into assets/site.js (one external script: no inline
//      script, no eval; NFR15).
//   2. The self-hosted fonts assets/*.woff2 (SIL OFL 1.1, licences/) are hashed (FR9.5).
//   3. styles/site.css becomes assets/site.css, with url("font:<name>") replaced by the hashed
//      font file name (relative to the stylesheet, which is served from the same folder).
//
// The generated files are committed: scripts/scan_output.py and the site store read the
// static sources from assets/. `node scripts/hash-assets.mjs --check` writes nothing and exits
// 1 when any generated file is out of date.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

// Every path below is relative to the package root, wherever the script is started from.
process.chdir(fileURLToPath(new URL("..", import.meta.url)));

const FONTS = [
  "cormorant-garamond",
  "inter",
  "source-serif-4",
  "source-serif-4-italic",
  "mrs-saint-delafield",
];
const CSS_HEADER =
  "/* Generated by scripts/hash-assets.mjs from styles/site.css. Do not edit. */\n";
const check = process.argv.includes("--check");

const hashOf = (data) => createHash("sha256").update(data).digest("hex").slice(0, 10);

async function bundleClient() {
  const result = await build({
    absWorkingDir: process.cwd(),
    entryPoints: ["src/client/main.ts"],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2020",
    minify: true,
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  return result.outputFiles[0].text;
}

function buildCss(fontFiles) {
  const source = readFileSync("styles/site.css", "utf-8");
  const css = source.replace(/url\("font:([a-z0-9-]+)"\)/g, (_match, name) => {
    const file = fontFiles[name];
    if (!file) throw new Error(`styles/site.css names unknown font '${name}'`);
    return `url("${file}")`;
  });
  return CSS_HEADER + css;
}

function staticAssetsModule(entries) {
  const line = ({ path, source }) => `{ path: "${path}", source: "${source}" }`;
  const [site, script, ...fonts] = entries;
  return [
    "// Generated by scripts/hash-assets.mjs. Do not edit; run `npm run hash-assets`.",
    "export const STATIC_ASSETS = {",
    `  site: ${line(site)},`,
    `  script: ${line(script)},`,
    "  fonts: [",
    ...fonts.map((font) => `    ${line(font)},`),
    "  ],",
    "} as const;",
    "",
    "/** Every static asset a release needs, in a fixed order (C11 `staticAssets`). */",
    "export const STATIC_ASSET_PATHS: readonly string[] = [",
    ...entries.map(({ path }) => `  "${path}",`),
    "];",
    "",
  ].join("\n");
}

const fontEntries = FONTS.map((name) => {
  const source = `assets/${name}.woff2`;
  const file = `${name}.${hashOf(readFileSync(source))}.woff2`;
  return { name, file, path: `/assets/${file}`, source };
});
const css = buildCss(Object.fromEntries(fontEntries.map(({ name, file }) => [name, file])));
const script = await bundleClient();
const entries = [
  { path: `/assets/site.${hashOf(css)}.css`, source: "assets/site.css" },
  { path: `/assets/site.${hashOf(script)}.js`, source: "assets/site.js" },
  ...fontEntries.map(({ path, source }) => ({ path, source })),
];
const outputs = [
  ["assets/site.css", css],
  ["assets/site.js", script],
  ["src/static-assets.ts", staticAssetsModule(entries)],
];

if (check) {
  const stale = outputs.filter(([file, text]) => {
    try {
      return readFileSync(file, "utf-8") !== text;
    } catch {
      return true;
    }
  });
  for (const [file] of stale) console.error(`hash-assets: ${file} is out of date`);
  process.exitCode = stale.length > 0 ? 1 : 0;
} else {
  for (const [file, text] of outputs) writeFileSync(file, text);
}
