// Builds the simulated public export (prototype/export/) from the approved-publication snapshot.
//
// Usage (from prototype/):  node tools/build-export.cjs
//
// The design-review data (data.js) holds every launch candidate, including unapproved ones. This
// script applies the publication rule and writes a self-contained export that contains ONLY
// approved projects — their allow-listed fields (FR4.10), derived badges, and the assets they
// use. Export pages load export/publication.js and never data.js. Featured order, categories,
// counts, catalog entries, case studies and direct routes all derive from this one snapshot.
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "export");

// --- load the design-review data -----------------------------------------------------------
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(ROOT, "data.js"), "utf8"), sandbox);
const D = sandbox.window.PORTFOLIO;

// --- publication rule (FR7.1, FR10.1, FR10.6, FR10.7) --------------------------------------
const RULE = "A project is exported only if it has a published version, its content is approved, and no rights review is outstanding. Its live URL is exported only if authorized.";
const hasPublishedVersion = (s) => s === "Published" || s === "Changes since last publish";
const isApproved = (p) => !!p.publication && hasPublishedVersion(p.publication.status) &&
  /^approved/.test(p.publication.content) && p.publication.rights !== "outstanding";
const liveUrlAuthorized = (p) => /^authorized/.test(p.publication.liveUrl);

const approved = D.projects.filter(isApproved);
const featuredOrder = approved.filter((p) => p.featured).sort((a, b) => a.featured - b.featured).map((p) => p.slug);

// --- snapshot: allow-listed fields only (FR4.10) -------------------------------------------
const projects = approved.map((p) => {
  const liveUrl = liveUrlAuthorized(p) ? p.access.liveUrl : null;
  const badges = D.badges({ access: { ...p.access, liveUrl, liveWithheld: false }, repos: p.repos })
    .map((b) => ({ text: b.text, tone: b.tone }));
  const narrative = {};
  for (const [k] of D.narrativeOrder) if (p.narrative[k]) narrative[k] = p.narrative[k];
  return {
    slug: p.slug, title: p.title, category: p.category, icon: p.icon,
    featured: featuredOrder.indexOf(p.slug) + 1,
    meta: [...p.meta], summary: p.summary,
    lead: { src: p.lead.src, alt: p.lead.alt, kind: p.lead.kind, pos: p.lead.pos },
    gallery: p.gallery.map((g) => ({ src: g.src, alt: g.alt, caption: g.caption, kind: g.kind, pos: g.pos })),
    narrative, files: [], badges,
    access: { liveUrl },
    repos: p.repos.filter((r) => r.visibility === "public").map((r) => ({ visibility: "public", url: r.url, licence: r.licence })),
  };
});
const categories = D.categories
  .filter((c) => projects.some((p) => p.category === c.id))
  .map((c) => ({ id: c.id, name: c.name, sub: c.sub, icon: c.icon, image: { src: c.image.src, kind: c.image.kind, alt: "" } }));
// A category tile may only use an image that belongs to an exported project.
const exportedImages = new Set(projects.flatMap((p) => [p.lead.src, ...p.gallery.map((g) => g.src)]));
for (const c of categories) {
  if (!exportedImages.has(c.image.src)) {
    const p = projects.find((x) => x.category === c.id);
    c.image = { src: p.lead.src, kind: p.lead.kind, alt: "" };
  }
}
const snapshot = { rule: RULE, approvals: "simulated for the prototype — nothing is approved for publication", projects, categories };

// --- write the export ----------------------------------------------------------------------
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const copy = (rel) => { fs.mkdirSync(path.dirname(path.join(OUT, rel)), { recursive: true }); fs.copyFileSync(path.join(ROOT, rel), path.join(OUT, rel)); };

fs.writeFileSync(path.join(OUT, "publication.js"),
`// GENERATED by tools/build-export.cjs — do not edit.
// Approved-publication snapshot: the only data the simulated public export loads.
window.PORTFOLIO = (() => {
  "use strict";
  const snapshot = ${JSON.stringify(snapshot, null, 2)};
  const narrativeOrder = ${JSON.stringify(D.narrativeOrder.map(([k, l]) => [k, l]))};
  return {
    mode: "export",
    categories: snapshot.categories,
    projects: snapshot.projects,
    badges: (p) => p.badges,
    narrativeOrder,
    byCategory: (id) => snapshot.projects.filter((p) => p.category === id),
    find: (slug) => snapshot.projects.find((p) => p.slug === slug),
    cat: (id) => snapshot.categories.find((c) => c.id === id),
  };
})();
`);

for (const f of ["styles.css", "shell.js", "site.js", "app.js", "icons.js"]) copy(f);
for (const f of fs.readdirSync(path.join(ROOT, "fonts"))) copy(path.join("fonts", f));
const assets = new Set([...exportedImages, ...categories.map((c) => c.image.src)]);
for (const a of assets) copy(a);

const bannerExport = "<strong>Simulated public export</strong> · Built only from the approved-publication snapshot · Approvals here are simulated for the prototype; nothing is published";
for (const page of ["index.html", "catalog.html", "project.html"]) {
  let html = fs.readFileSync(path.join(ROOT, page), "utf8");
  if (!html.includes('<script src="data.js" defer></script>')) throw new Error(`${page}: data.js script tag not found`);
  html = html.replace('<script src="data.js" defer></script>', '<script src="publication.js" defer></script>');
  html = html.replace(/<p><strong>Design review view<\/strong>[^]*?<\/p>/, `<p>${bannerExport}</p>`);
  fs.writeFileSync(path.join(OUT, page), html);
}

console.log(`export built: ${projects.length} project(s) [${projects.map((p) => p.slug).join(", ")}], ` +
  `${categories.length} categor(y/ies), ${assets.size} asset(s); ${D.projects.length - projects.length} candidate(s) excluded`);
